import assert from 'node:assert/strict';
import { measure, mergeObservations, recordRecommendations } from './performance_tracker.mjs';
const report = { generatedAt: '2026-09-27T13:30:00Z', asOf: '2026-09-23', next: '2026-09-28', ruleVersion: 2,
  selected: [{ code: '000001', close: 100, setup: 'A', name: '테스트', themes: ['테스트'], high52: 101 }] };
const ledger = { recommendations: [] };
recordRecommendations(ledger, report, 'first.json');
recordRecommendations(ledger, { ...report, selected: [{ ...report.selected[0], close: 120 }] }, 'second.json');
assert.equal(ledger.recommendations.length, 1);
const record = ledger.recommendations[0];
assert.equal(record.referenceClose, 100); assert.equal(record.sourceFile, 'first.json');
assert.equal(record.explanation.sourceAt, report.generatedAt);
assert.throws(() => recordRecommendations(ledger, { ...report, generatedAt: '2026-09-28T15:00:00Z' }, 'late.json'));
const make = (date, close) => ({ date, open: 100, high: close + 5, low: 90, close, volume: 100 });
const sessions = ['2026-09-28', '2026-09-29', '2026-09-30', '2026-10-01', '2026-10-02'];
const bars = [make('2026-09-23', 100), ...sessions.map((d, i) => make(d, 100 + i * 5))];
assert.equal(mergeObservations(record, bars, '2026-09-23', 'now', 'source'), null);
assert.equal(record.observations.length, 0);
assert.equal(measure(record, ['2026-09-23'], '2026-09-23').status, '첫 거래일 대기');
assert.equal(measure(record, [], '2026-09-23', '기준가 오류').status, '기준가 오류');
mergeObservations(record, bars, '2026-10-02', 'now', 'source');
mergeObservations(record, bars, '2026-10-02', 'again', 'source');
assert.equal(record.observations.length, 5);
const m = measure(record, sessions, '2026-10-02');
assert.equal(m.holdingReturns[1], 0); assert(Math.abs(m.holdingReturns[3] - .1) < 1e-12);
assert(Math.abs(m.holdingReturns[5] - .2) < 1e-12); assert.equal(m.holdingReturns[10], null);
assert.equal(m.maximumReturn, .25); assert(Math.abs(m.minimumReturn + .1) < 1e-12);
assert.equal(m.hit10, true);
assert(measure({ ...record, observations: record.observations.slice(1) }, sessions, '2026-10-02').status.includes('확인 필요'));
assert.equal(measure(record, [...sessions, '2026-10-05'], '2026-10-05').latestClose, undefined);
const adjusted = structuredClone(bars); adjusted[0].close = 50;
assert(mergeObservations(record, adjusted, '2026-10-02', 'now', 'source').includes('수정'));
const revised = structuredClone(bars); revised[1].close = 101;
assert(mergeObservations(record, revised, '2026-10-02', 'now', 'source').includes('수정'));
assert.equal(record.observations[0].close, 100);
recordRecommendations(ledger, { ...report, generatedAt: '2026-09-28T13:00:00Z', next: '2026-09-29' }, 'next.json');
assert.equal(ledger.recommendations.length, 2);
recordRecommendations(ledger, { ...report, ruleVersion: 3 }, 'v3.json');
recordRecommendations(ledger, { ...report, ruleVersion: 3 }, 'v3-repeat.json');
assert.equal(ledger.recommendations.length, 3);
assert.equal(ledger.recommendations.at(-1).id, '2026-09-28/000001/v3');
assert.equal(ledger.recommendations[0].ruleVersion, 2);
console.log('performance tracker checks passed');
